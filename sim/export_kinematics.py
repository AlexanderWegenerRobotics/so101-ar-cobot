from pathlib import Path

import mujoco
import numpy as np
import yaml

from controls.kinematics import load_kinematics
from interfaces.transforms import Pose, pose_error

ROOT = Path(__file__).resolve().parents[1]
MODEL_XML = ROOT / "sim" / "model" / "so101.xml"
KINEMATICS_YAML = ROOT / "config" / "kinematics.yaml"
ARM_JOINTS = ["shoulder_pan", "shoulder_lift", "elbow_flex", "wrist_flex", "wrist_roll"]
BASE_SITE = "baseframe"
TOOL_SITE = "gripperframe"


def rounded(values):
    return [round(float(v), 8) for v in values]


def export_kinematics(model, path=KINEMATICS_YAML):
    joints = []
    for name in ARM_JOINTS:
        joint = model.joint(name)
        body = model.jnt_bodyid[joint.id]
        joints.append({"name": name, "pos": rounded(model.body_pos[body]),
                       "quat": rounded(model.body_quat[body]), "axis": rounded(model.jnt_axis[joint.id])})
    site = model.site(TOOL_SITE)
    assert model.site_bodyid[site.id] == model.jnt_bodyid[model.joint(ARM_JOINTS[-1]).id], \
        "tool site must sit on the last arm joint's body"
    tool = {"pos": rounded(model.site_pos[site.id]), "quat": rounded(model.site_quat[site.id])}
    with open(path, "w") as f:
        f.write("# generated by sim/export_kinematics.py from sim/model/so101.xml, rerun it after model changes\n")
        yaml.safe_dump({"frame": "robot_base", "joints": joints, "tool": tool}, f,
                       sort_keys=False, default_flow_style=None)
    return path


def site_pose(model, data, name):
    site = model.site(name).id
    return Pose.from_rotation(data.site_xpos[site].copy(), data.site_xmat[site].reshape(3, 3).copy())


def check(model, kinematics, samples=5):
    data = mujoco.MjData(model)
    rng = np.random.default_rng(0)
    for _ in range(samples):
        q = []
        for joint in kinematics.joints:
            mj_joint = model.joint(joint.name)
            angle = rng.uniform(*model.jnt_range[mj_joint.id])
            data.qpos[model.jnt_qposadr[mj_joint.id]] = angle
            q.append(angle)
        mujoco.mj_forward(model, data)
        truth = site_pose(model, data, BASE_SITE).inverse() * site_pose(model, data, TOOL_SITE)
        error = pose_error(truth, kinematics.forward(q))
        print(f"position error {error['pos'] * 1000:.4f} mm  angle error {np.degrees(error['angle']):.4f} deg")


def main():
    model = mujoco.MjModel.from_xml_path(str(MODEL_XML))
    path = export_kinematics(model)
    print(f"wrote {path}")
    check(model, load_kinematics(path))


if __name__ == "__main__":
    main()
